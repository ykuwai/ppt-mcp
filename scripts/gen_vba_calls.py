#!/usr/bin/env python3
"""Generate the VBA bridge's direct calls, src/backend/vba/PptMcpCalls*.bas.

    uv run python scripts/gen_vba_calls.py

The add-in can run any call with CallByName, but CallByName reports every
failure inside PowerPoint as error 440, "Automation error", and drops
PowerPoint's own message ("Shapes.Item : Integer out of range." and the
like). A call written out, ``o.Item(a)``, keeps it. So for each object-model
member the routed tools use, this writes that call out, once per number of
arguments the member takes, and the dispatcher tries it before falling back
to CallByName for anything else.

The members are the PascalCase names used in the ppt_com modules that have a
VBA route (backend/vba/routes.py) and in the helpers they share, as far as
PowerPoint's type library (com_members.json) knows them. A test keeps the
generated files in step with that code; rebuild the add-in on Windows
afterwards (scripts/build_mac_vba_addin.py).
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
VBA = ROOT / "src" / "backend" / "vba"
sys.path.insert(0, str(ROOT / "src"))

# Helpers the routed implementations share, beyond their own modules.
SHARED = ["src/ppt_com/shape_lookup.py", "src/utils/*.py"]
MAX_ARGS = 8          # the dispatcher passes at most eight
HEADER = "' Generated by scripts/gen_vba_calls.py; do not edit by hand.\n"


def routed_modules():
    from backend.vba.routes import ROUTES

    return sorted({module.split(".")[1] for module, _ in ROUTES})


def used_members():
    files = [ROOT / "src" / "ppt_com" / f"{m}.py" for m in routed_modules()]
    for pattern in SHARED:
        files += sorted(ROOT.glob(pattern))
    used = set()
    for f in files:
        used |= set(re.findall(r"\.([A-Z][A-Za-z0-9_]*)\b", f.read_text(encoding="utf-8")))
    table = json.loads((VBA / "com_members.json").read_text(encoding="utf-8"))
    arity = {}
    for iface in table.values():
        for name, (kinds, params, nopt) in iface["members"].items():
            arity[name] = max(arity.get(name, 0), len(params))
    return {name: min(arity[name], MAX_ARGS) for name in sorted(used) if name in arity}


def _args(n):
    return ", ".join(f"ArgOf(f({3 + i}))" for i in range(n))


def generate() -> dict:
    """{module name: source} for every generated module."""
    members = used_members()
    by_letter = {}
    for name in members:
        by_letter.setdefault(name[0].upper(), []).append(name)
    modules = {}
    for letter, names in sorted(by_letter.items()):
        mod = f"PptMcpCalls{letter}"
        lines = [f'Attribute VB_Name = "{mod}"', HEADER.rstrip("\n"), "Option Explicit",
                 f"Public Function Call{letter}(o As Object, kind As String, m As String, f() As String, "
                 "n As Integer, ByRef r As Variant) As Boolean",
                 f"    Call{letter} = True",
                 "    Select Case m"]
        for name in names:
            lines += [f'        Case "{name}"',
                      '            If kind = "l" Then',
                      f"                o.{name} = ArgOf(f(3))",
                      '            ElseIf kind = "s" Then',
                      f"                Set o.{name} = ArgOf(f(3))",
                      "            Else",
                      "                Select Case n"]
            for k in range(members[name] + 1):
                call = f"o.{name}" if k == 0 else f"o.{name}({_args(k)})"
                lines.append(f"                    Case {k}: Assign r, {call}")
            lines += [f"                    Case Else: Call{letter} = False",
                      "                End Select",
                      "            End If"]
        lines += ["        Case Else", f"            Call{letter} = False", "    End Select", "End Function", ""]
        modules[mod] = "\n".join(lines)
    router = ['Attribute VB_Name = "PptMcpCalls"', HEADER.rstrip("\n"), "Option Explicit",
              "Public Sub Assign(ByRef dst As Variant, ByVal src As Variant)",
              "    If IsObject(src) Then",
              "        Set dst = src",
              "    Else",
              "        dst = src",
              "    End If",
              "End Sub",
              "' Runs the call written out when there is one; False sends it to CallByName.",
              "Public Function Direct(o As Object, kind As String, m As String, f() As String, "
              "n As Integer, ByRef r As Variant) As Boolean",
              "    Select Case UCase$(Left$(m, 1))"]
    router += [f'        Case "{L}": Direct = Call{L}(o, kind, m, f, n, r)' for L in sorted(by_letter)]
    router += ["        Case Else: Direct = False", "    End Select", "End Function", ""]
    modules["PptMcpCalls"] = "\n".join(router)
    return modules


def main():
    modules = generate()
    for old in VBA.glob("PptMcpCalls*.bas"):
        if old.stem not in modules:
            old.unlink()
    for name, text in modules.items():
        (VBA / f"{name}.bas").write_bytes(text.replace("\n", "\r\n").encode("ascii"))
    print(f"wrote {len(modules)} modules for {len(used_members())} members")


if __name__ == "__main__":
    main()
