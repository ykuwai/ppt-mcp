class Call:
    """What the Windows code reaches through ``ppt`` while it runs on VBA.

    The deck is looked up when the Windows code first asks for it, not
    before: some tools need none (listing SmartArt layouts), and with no deck
    open there is none to find.
    """

    def __init__(self, app, pres=None, find_pres=None):
        self.app = app
        self._pres = pres
        self._find_pres = find_pres

    @property
    def pres(self):
        if self._pres is None and self._find_pres is not None:
            self._pres = self._find_pres()
        return self._pres

    def window(self):
        windows = self.pres.Windows
        return windows(1) if windows.Count else None


_CALL: contextvars.ContextVar = contextvars.ContextVar("ppt_mcp_vba_call", default=None)


def current() -> Optional[Call]:
    """The VBA call running on this thread, or None."""
    return _CALL.get()


def active() -> bool:
    return _CALL.get() is not None


def _same_deck(app, name, full_name):
    """The bridge's presentation for the deck the Apple Event side resolved."""
    matches = []
    for i in range(1, app.Presentations.Count + 1):
        pres = app.Presentations(i)
        if pres.Name == name:
            matches.append(pres)
    if len(matches) > 1:
        exact = [p for p in matches if p.FullName == full_name]
        matches = exact or matches
    if not matches:
        raise RuntimeError(f"PowerPoint's VBA does not see the presentation '{name}'.")
    return matches[0]


def run(com_impl: Callable, *args, **kwargs) -> Any:
    """Run a Windows implementation on PowerPoint for Mac through the add-in.

    The deck is the one the Apple Event side resolves, so the session target
    and a deck named by the call are honoured as for every other tool.
    """
    from backend import ppt

    return _run(_SESSION.bridge(ppt._get_app_impl()), com_impl, args, kwargs)


@contextlib.contextmanager
def _temp_files_powerpoint_can_read():
    """Temporary files in PowerPoint's container while Windows code runs.

    The Windows code writes some files for PowerPoint to read (a snapshot of
    a deck to insert slides from, for one); PowerPoint is sandboxed, and
    anywhere outside its container macOS asks the user for access first.
    Only the worker runs tool code, so this is set and put back on one thread.
    """
    folder = INSTALL_DIR / "tmp"
    folder.mkdir(parents=True, exist_ok=True)
    before = tempfile.tempdir
    tempfile.tempdir = str(folder)
    try:
        yield
    finally:
        tempfile.tempdir = before


def _deck_for(app):
    """The bridge's presentation for the deck the Apple Event side resolves."""
    from backend import ppt

    # Asked outside the VBA call: inside it, the wrapper hands back the call's
    # own deck, which is what is being looked up.
    token = _CALL.set(None)
    try:
        mac_pres = ppt._get_pres_impl()
    finally:
        _CALL.reset(token)
    name = mac_pres.name()
    if not isinstance(name, str):
        # With no deck open, `active presentation` is a missing value rather
        # than an error.
        raise RuntimeError(
            "No presentation is open in PowerPoint. "
            "Use ppt_create_presentation or ppt_open_presentation first.")
    return _same_deck(app, name, mac_pres.full_name())


def _run(bridge: Bridge, com_impl: Callable, args, kwargs) -> Any:
    if bridge.stale:
        bridge.release()
    app = bridge.application()
    try:
        token = _CALL.set(Call(app, find_pres=lambda: _deck_for(app)))
        try:
            with _temp_files_powerpoint_can_read():
                return com_impl(*args, **kwargs)
        finally:
            _CALL.reset(token)
    finally:
        try:
            bridge.release()
        except Exception:  # noqa: BLE001 - handles go with PowerPoint anyway
            logger.debug("Could not release the VBA bridge's handles", exc_info=True)


def _noted(result, failure_note: str, recreated_note: str):
    """``result`` of an Apple Event implementation, with a note on why the
    add-in did not take the call.

    A refusal (a failure naming its ``platform``) gets ``failure_note`` as
    its ``hint``. A success whose shape was
    recreated through the clipboard gets ``recreated_note`` among its
    ``warnings``. Anything else, and anything that is not a JSON object, is
    handed back as it was. A result given as JSON text goes back as JSON text.
    """
    as_text = isinstance(result, str)
    try:
        body = json.loads(result) if as_text else result
    except ValueError:
        return result
    if not isinstance(body, dict):
        return result
    body = dict(body)  # a noted result is a new one; the original stays as it was
    if "error" in body:
        if "platform" not in body:
            # Not a refusal: the add-in would have failed the same way.
            return result
        body["hint"] = f"{body['hint']} {failure_note}" if body.get("hint") else failure_note
    elif any("was recreated" in str(w) for w in body.get("warnings") or []):
        body["warnings"] = list(body["warnings"]) + [recreated_note]
    else:
        return result
    return json.dumps(body) if as_text else body


def routed(com_impl: Callable, mac_impl: Callable, condition: Callable[[dict], bool]) -> Callable:
    """An implementation that takes the VBA route when it can and should.

    ``condition`` gets the call's arguments by name and says whether this call
    needs the route; when it does not, when the route is off, or when the
    add-in cannot be loaded, the Apple Event implementation runs instead.
    """
    signature = inspect.signature(com_impl)

    @functools.wraps(mac_impl)
    def impl(*args, **kwargs):
        if active():
            return mac_impl(*args, **kwargs)
        try:
            bound = signature.bind(*args, **kwargs)
        except TypeError:
            return mac_impl(*args, **kwargs)
        bound.apply_defaults()
        if not ENABLED:
            # The condition can cost an Apple Event, so it is asked only when
            # there is a note to add.
            result = mac_impl(*args, **kwargs)
            noted = _noted(result, OFF_NOTE, OFF_RECREATED_NOTE)
            return noted if noted is not result and condition(bound.arguments) else result
        if not condition(bound.arguments):
            return mac_impl(*args, **kwargs)
        # Checked before anything is written: a tool makes several calls, and
        # one refused halfway would leave the earlier ones done.
        for value in bound.arguments.values():
            _check_text(value)
        from backend import ppt

        try:
            bridge = _SESSION.bridge(ppt._get_app_impl())
        except VbaUnavailable as e:
            # _SESSION has logged it, once for each reason.
            note = _unavailable_note(e)
            return _noted(mac_impl(*args, **kwargs), note, note)
        return _run(bridge, com_impl, args, kwargs)

    impl.vba_route = (com_impl, condition)
    return impl


